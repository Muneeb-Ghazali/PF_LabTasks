#include <stdio.h>
int main ()
{
	printf("********** C ESCAPE SEQUENCES REFERENCE **********\n---------------------------------------------------------\n");

	printf("1.\t To print a double quote, write:\t\t\t \\\" ");

	printf("\n2.\t To print a literal backslash, write:\t\t \\\\");

	printf("\n3.\t To insert a newline break, write:\t\t\t \\n");

	printf("\n4.\t To insert a horizontal tab stop, write:\t \\t ");

	printf("\n5.\t To print a percent sign, write:\t\t\t %%%%");

	printf("\n----------------------------------------------------- \n");
return 0;

}